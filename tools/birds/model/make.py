def run(cmd, env=None):
    e = dict(os.environ); e.update(env or {})
    r = subprocess.run(cmd, env=e, capture_output=True, text=True)
    if r.returncode:
        sys.stderr.write(r.stdout[-2000:] + r.stderr[-2000:])
        raise SystemExit('make.py: failed: ' + ' '.join(cmd))


def strip(o):
    """the served copy: every number kept, every note dropped"""
    if isinstance(o, dict):
        return {k: strip(v) for k, v in o.items() if not isinstance(v, str)}
    if isinstance(o, list):
        if any(isinstance(x, str) for x in o) and any(not isinstance(x, str) for x in o):
            return [strip(x) for x in o if not isinstance(x, str)]   # (numbers with a text label: the label dropped)
        return [strip(x) for x in o]   # (a list of names, such as a rig's solved channels, is data: kept)
    return o


def make(tmp):
    S = json.load(open(os.path.join(HERE, 'settings.json')))
    ss = os.path.join(tmp, 'stroke_scale.json'); json.dump(S['stroke_scale'], open(ss, 'w'))
    raw, solved = os.path.join(tmp, 'raw.json'), os.path.join(tmp, 'solved.json')
    run([sys.executable, '-I', os.path.join(HERE, 'build_model.py'), os.path.join(HERE, 'data'), raw],
        {'STROKE_SCALE': ss, 'HERON': json.dumps(S['heron'])})
    run(['node', os.path.join(HERE, 'solve.js'), FORM, raw, solved])
    full = open(solved).read()
    served = HEAD + 'self.WINGMODEL_DATA = ' + json.dumps(strip(json.loads(full)), separators=(',', ':')) + ';\n'
    return full, served


def main():
    check = sys.argv[1:] == ['--check']
    with tempfile.TemporaryDirectory() as tmp:
        full, served = make(tmp)
    if check:
        bad = 0
        for p, t in ((FULL, full), (SERVED, served)):
            if not os.path.exists(p) or open(p, encoding='utf-8').read() != t:
                print('::error::' + os.path.relpath(p, REPO) + ' is not what tools/birds/model/make.py makes (run it and commit the result)'); bad = 1
        if bad: sys.exit(1)
        print('make.py: model.js and model_full.json are what the data and the settings make (%d bytes served)' % len(served.encode()))
        return
    open(FULL, 'w').write(full); open(SERVED, 'w').write(served)
    print('make.py: wrote %s (%d bytes) and %s' % (os.path.relpath(SERVED, REPO), len(served.encode()), os.path.relpath(FULL, REPO)))


if __name__ == '__main__':
    main()
